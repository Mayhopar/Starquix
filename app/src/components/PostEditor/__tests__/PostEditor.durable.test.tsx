import 'fake-indexeddb/auto';
import { webcrypto } from 'node:crypto';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import * as Y from 'yjs';
import { db } from '@/db';
import { projectFsRuntime } from '@/test/projectFsRuntime';
import { markFilesTruth } from '@/utils/localMode';
import { localPageId } from '@/utils/localMode';
import { setActiveSaveProjectId } from '@/services/pendingProjectMutations';
import { parseFrontmatter, setLocalContentSource, contentOps } from '@/core/collections/content-ops';
import { readAcceptedPost } from '@/services/durableEdits/featureAcceptance';
const state = vi.hoisted(() => ({ doc: null as Y.Doc | null }));
vi.mock('@/store/hooks', () => ({ useDispatch: () => vi.fn(), useEditorDoc: () => state.doc, useYjsValue: () => [] }));
vi.mock('@/context/UndoContext', () => ({ useUndoContext: () => ({ takeSnapshot: vi.fn() }), useOptionalUndoContext: () => null }));
vi.mock('@/context/PostEditorContext', () => ({ usePostEditor: () => ({ openPost: vi.fn() }) }));
vi.mock('@/hooks/useLocalProjectPath', () => ({ useLocalProjectPath: () => null }));
vi.mock('../PostBodyEditor', () => ({ PostBodyEditor: () => <div /> }));
import { PostEditor } from '../PostEditor';
const file = 'src/content/posts/a.md';
const source = '---\ntitle: Old\n---\nBody';
let projectId: string;
let runtime: ReturnType<typeof projectFsRuntime>;
beforeEach(async () => {
  vi.stubGlobal('crypto', webcrypto); await db.delete(); await db.open();
  projectId = `post_frontmatter_${crypto.randomUUID()}`; markFilesTruth(projectId); setActiveSaveProjectId(projectId);
  setLocalContentSource(`wc://${projectId}`); state.doc = new Y.Doc(); state.doc.getMap('meta').set('projectId', projectId);
  runtime = projectFsRuntime(projectId, { [file]: source });
});
afterEach(() => { runtime.close(); setLocalContentSource(null); setActiveSaveProjectId(null); state.doc?.destroy(); vi.restoreAllMocks(); vi.unstubAllGlobals(); });
it('accepts title input before blur and restores the accepted title when storage refuses the next edit', async () => {
  const view = render(<PostEditor collectionName="posts" post={{ slug: 'a', filePath: file, ...parseFrontmatter(source) }} onPostUpdate={() => {}} />);
  const title = await screen.findByRole('textbox', { name: 'Title' });
  fireEvent.change(title, { target: { value: 'Accepted' } });
  await act(async () => { await vi.waitFor(async () => expect(await db.durableEdits.count()).toBe(1), { timeout: 500 }); });
  vi.spyOn(db.durableEditCheckpoints, 'add').mockRejectedValue(new Error('quota'));
  fireEvent.change(title, { target: { value: 'Rejected' } });
  await waitFor(() => expect(title).toHaveValue('Accepted'));
  expect((await readAcceptedPost(projectId, 'posts', 'a')).frontmatter.title).toBe('Accepted');
  expect(runtime.read(file)).toBe(source); view.unmount();
});
it('discovers pending accepted post bytes when reopening before source materialization', async () => {
  const { acceptPostWrite } = await import('@/services/durableEdits/featureAcceptance');
  await acceptPostWrite(projectId, 'posts', 'a', { title: 'Accepted' }, 'Accepted body');
  db.close(); await db.open();
  const collections = await contentOps.fetchCollections();
  expect(collections[0].posts[0]).toMatchObject({ frontmatter: { title: 'Accepted' }, body: 'Accepted body' });
});
it('accepts rapid property revisions on an unparseable body against the preceding accepted baseline', async () => {
  const invalidFile = 'src/content/posts/b.mdx';
  const invalid = '---\ntitle: Old\n---\nimport {';
  runtime.close(); runtime = projectFsRuntime(projectId, { [invalidFile]: invalid });
  const view = render(<PostEditor collectionName="posts" post={{ slug: 'b', filePath: invalidFile, ...parseFrontmatter(invalid) }} onPostUpdate={() => {}} />);
  const title = await screen.findByRole('textbox', { name: 'Title' });
  fireEvent.change(title, { target: { value: 'One' } });
  fireEvent.change(title, { target: { value: 'Two' } });
  await waitFor(async () => expect(await db.durableEdits.count()).toBe(2));
  expect(title).toHaveValue('Two');
  expect((await readAcceptedPost(projectId, 'posts', 'b')).frontmatter.title).toBe('Two');
  expect(runtime.read(invalidFile)).toBe(invalid); view.unmount();
});
it('keeps the post queue writable if accepted rename cleanup cannot enter storage', async () => {
  const oldSlug = 'untitled-123'; const renameFile = `src/content/posts/${oldSlug}.mdx`;
  const raw = '---\ntitle: ""\n---\nBody';
  runtime.close(); runtime = projectFsRuntime(projectId, { [renameFile]: raw });
  state.doc!.getMap('pages').set(localPageId(`/posts/${oldSlug}`), new Y.Map());
  state.doc!.getMap('pages').set('home', new Y.Map());
  const writeCheckpoint = db.durableEditCheckpoints.add.bind(db.durableEditCheckpoints);
  let calls = 0;
  vi.spyOn(db.durableEditCheckpoints, 'add').mockImplementation((...args) => {
    if (++calls === 3) return Promise.reject(new Error('cleanup quota')) as ReturnType<typeof writeCheckpoint>;
    return writeCheckpoint(...args);
  });
  const view = render(<PostEditor collectionName="posts" post={{ slug: oldSlug, filePath: renameFile, ...parseFrontmatter(raw) }} onPostUpdate={() => {}} />);
  const title = await screen.findByRole('textbox', { name: 'Title' });
  fireEvent.change(title, { target: { value: 'Renamed' } });
  await waitFor(async () => expect(await db.durableEdits.count()).toBe(1));
  fireEvent.blur(title);
  await waitFor(() => expect(calls).toBe(3));
  expect(await db.durableEdits.count()).toBe(2);
  fireEvent.change(title, { target: { value: 'Still writable' } });
  await waitFor(async () => expect(await db.durableEdits.count()).toBe(3));
  expect((await readAcceptedPost(projectId, 'posts', 'renamed')).frontmatter.title).toBe('Still writable');
  view.unmount();
});
